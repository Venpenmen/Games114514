import {expect,test} from '@playwright/test'
import {loginPlayer,registerPlayer} from './account-fixtures.ts'

test('real browsers transfer a seat between devices and manage the account',async({browser,baseURL})=>{
  const contexts=await Promise.all(Array.from({length:4},(_,i)=>browser.newContext({
    baseURL,viewport:i===3?{width:390,height:844}:{width:1280,height:850},
  })))
  try {
    const [first,b,c,second]=await Promise.all(contexts.map(context=>context.newPage()))
    await first.goto('/')
    await expect(first.getByRole('heading',{name:'登录'})).toBeVisible()
    await expect(first.getByRole('heading',{name:'游戏大厅'})).toHaveCount(0)
    const username=await registerPlayer(first,'双设备玩家')
    await first.locator('.game-card').filter({has:first.getByRole('heading',{name:'诡吹灯',exact:true})})
      .getByRole('button',{name:'创建房间'}).click()
    await expect(first.getByRole('heading',{name:/诡吹灯 · \d{6}/})).toBeVisible()
    const invite=first.url()
    await Promise.all([b,c].map(async(page,i)=>{
      await page.goto(invite)
      await registerPlayer(page,'同桌玩家'+i)
      await expect(page.getByRole('button',{name:'准备',exact:true})).toBeVisible()
    }))
    await Promise.all([first,b,c].map(page=>page.getByRole('button',{name:'准备',exact:true}).click()))
    await first.getByRole('button',{name:'开始游戏'}).click()
    const role=first.locator('.role-label strong')
    await expect(role).toBeVisible()
    const secret=await role.textContent()
    await second.goto('/')
    await loginPlayer(second,username)
    await expect(second.locator('.role-label')).toHaveCount(0)
    await second.getByRole('button',{name:'切换到当前设备操作'}).click()
    await expect(second.locator('.role-label strong')).toHaveText(secret!)
    await expect(first.getByRole('status')).toHaveText('本标签页正在只读查看')
    await first.getByRole('button',{name:'返回大厅',exact:true}).click()
    await expect(first.getByRole('heading',{name:'游戏大厅'})).toBeVisible()
    await expect(first.locator('.role-label')).toHaveCount(0)
    await first.getByRole('button',{name:/双设备玩家/}).click()
    await expect(first.getByRole('heading',{name:'个人资料'})).toBeVisible()
    await first.getByRole('button',{name:'编辑资料'}).click()
    await first.getByRole('textbox',{name:'昵称'}).fill('改名玩家')
    await first.getByRole('button',{name:'更换头像'}).click()
    const avatars=first.getByRole('dialog',{name:'选择头像'})
    await avatars.getByRole('button',{name:'头像 🐰'}).click()
    await avatars.getByRole('button',{name:'取消'}).click()
    await expect(first.getByRole('button',{name:'更换头像'})).toHaveText('🐱')
    await first.getByRole('button',{name:'更换头像'}).click()
    await avatars.getByRole('button',{name:'头像 🐰'}).click()
    await avatars.getByRole('button',{name:'确认头像'}).click()
    await first.getByRole('button',{name:'账户安全',exact:true}).click()
    await first.getByRole('button',{name:'个人资料',exact:true}).click()
    await expect(first.getByRole('textbox',{name:'昵称'})).toHaveValue('改名玩家')
    await first.getByRole('button',{name:'保存修改'}).click()
    await expect(first.getByRole('status')).toHaveText('资料已保存')
    await first.getByRole('button',{name:'账户安全',exact:true}).click()
    await first.getByRole('button',{name:'退出所有其他设备'}).click()
    await first.getByRole('dialog').getByRole('button',{name:'确认撤销'}).click()
    await expect(second.getByRole('heading',{name:'登录'})).toBeVisible()
    await expect(second.locator('.role-label')).toHaveCount(0)
    await expect(first.getByText(/当前设备/).first()).toBeVisible()
  } finally {
    await Promise.all(contexts.map(context=>context.close()))
  }
})

test('account history keeps filters and pagination across responsive details',async({page})=>{
  await page.goto('/')
  await registerPlayer(page,'历史验收')
  await expect(page.locator('.game-card')).toHaveCount(3)
  const profile=await (await page.request.get('/api/me')).json()
  // The UI fixture crosses the existing API's 20-row boundary without playing 23 matches.
  const matches=Array.from({length:23},(_,i)=>({
    match_id:String(i),game_id:i<2?'ghost-candle':'dice-werewolf',started_at:1_700_000_000_000-i*86_400_000,
    finished_at:1_700_000_100_000-i*86_400_000,result:{winners:[profile.id]},players:[
      {player_id:profile.id,nickname_snapshot:'历史验收',score:23-i,rank:1,outcome:'win'},
    ],
  }))
  await page.route('**/api/history?*',async route=>{
    const offset=Number(new URL(route.request().url()).searchParams.get('offset'))
    await route.fulfill({json:{matches:matches.slice(offset,offset+20),more:offset+20<matches.length,
      totals:[{game_id:'ghost-candle',played:2,won:2,best_score:null},{game_id:'dice-werewolf',played:21,won:21,best_score:21}]}})
  })
  await page.getByRole('button',{name:/历史验收/}).click()
  const nav=page.getByRole('navigation',{name:'个人中心'})
  await nav.getByRole('button',{name:'游戏战绩'}).click()
  await expect(page.getByText('总对局数').locator('..')).toContainText('23')
  await nav.getByRole('button',{name:'历史对局'}).click()
  await page.getByLabel('游戏类型').selectOption('dice-werewolf')
  await page.getByLabel('时间顺序').selectOption('oldest')
  await expect(page.getByRole('cell',{name:'1 分 · 第 1 名',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'下一页'}).click()
  await expect(page.getByText('第 2 页')).toBeVisible()
  const details=page.getByRole('button',{name:'查看详情'}).first()
  await details.click()
  const drawer=page.getByRole('dialog',{name:'对局详情'})
  await expect(drawer).toBeVisible()
  await page.screenshot({path:'work/logs/p20-7-1-desktop-drawer.png'})
  await page.keyboard.press('Escape')
  await expect(details).toBeFocused()
  await expect(page.getByText('第 2 页')).toBeVisible()
  for(const [width,height] of [[1920,1080],[1366,768],[1280,720],[390,844],[375,667],[320,640]]) {
    await page.setViewportSize({width,height})
    await expect(nav).toBeVisible()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  }
  await details.click()
  await expect(drawer).toBeVisible()
  expect(Math.round((await drawer.boundingBox())!.width)).toBe(320)
  await page.screenshot({path:'work/logs/p20-7-1-mobile-detail.png'})
  await drawer.getByRole('button',{name:'返回历史列表'}).click()
  await expect(page.getByLabel('时间顺序')).toHaveValue('oldest')
  await expect(page.getByText('第 2 页')).toBeVisible()
  await page.getByLabel('比赛结果').selectOption('loss')
  await expect(page.getByText('暂无符合条件的对局')).toBeVisible()
  await nav.getByRole('button',{name:'账户安全'}).click()
  await page.getByRole('button',{name:'修改密码'}).click()
  const password=page.getByRole('dialog',{name:'修改密码'})
  await page.setViewportSize({width:320,height:400})
  await password.getByLabel('当前密码').fill('browser test phrase')
  await password.getByLabel('新密码',{exact:true}).fill('new browser test phrase')
  await password.getByLabel('确认新密码').fill('new browser test phrase')
  await password.getByRole('button',{name:'显示密码'}).click()
  await expect(password.getByLabel('当前密码')).toHaveAttribute('type','text')
  await password.getByRole('button',{name:'保存修改'}).click()
  await expect(page.getByRole('status')).toHaveText('密码已更新，其他设备已退出')
  await page.getByRole('button',{name:'返回大厅',exact:true}).click()
  await expect(page.locator('.game-card')).toHaveCount(3)
})
