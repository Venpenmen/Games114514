import {expect,test} from '@playwright/test'
import {registerPlayer} from './account-fixtures.ts'

test('one seat, one writable tab and browser history preserve membership',async({context,page})=>{
  await page.goto('/')
  await registerPlayer(page,'席位验收')
  const create=page.locator('.game-card').filter({has:page.getByRole('heading',{name:'诡吹灯',exact:true})})
    .getByRole('button',{name:'创建房间'})
  await create.click()
  await expect(page.getByRole('button',{name:'准备',exact:true})).toBeVisible()
  const invite=page.url()
  const other=await context.newPage()
  await other.goto(invite)
  await expect(other.getByText('本标签页正在只读查看')).toBeVisible()
  await other.getByRole('button',{name:'接管操作'}).click()
  await expect(other.getByRole('button',{name:'准备',exact:true})).toBeVisible()
  await expect(page.getByText('本标签页正在只读查看')).toBeVisible()
  await other.reload()
  await expect(other.getByRole('button',{name:'准备',exact:true})).toBeVisible()
  await other.getByRole('button',{name:'游戏规则'}).click()
  await expect(other.getByRole('dialog')).toBeVisible()
  await other.evaluate(()=>history.back())
  await expect(other.getByRole('dialog')).toBeHidden()
  await expect(other).toHaveURL(invite)
  await other.evaluate(()=>history.back())
  await expect(other.getByRole('heading',{name:'游戏大厅'})).toBeVisible()
  await expect(other.getByRole('button',{name:'返回已占席房间'})).toBeVisible()
  await other.locator('.game-card').filter({has:other.getByRole('heading',{name:'骰子狼人杀',exact:true})})
    .getByRole('button',{name:'创建房间'}).click()
  await expect(other.getByRole('alert')).toContainText('已占据房间')
  await other.evaluate(()=>history.forward())
  await expect(other.getByRole('button',{name:'准备',exact:true})).toBeVisible()
  await other.getByRole('button',{name:'解散房间'}).click()
  await expect(other.getByRole('heading',{name:'游戏大厅'})).toBeVisible()
  await expect(other.getByRole('button',{name:'返回已占席房间'})).toHaveCount(0)
  await expect(page.getByRole('heading',{name:'游戏大厅'})).toBeVisible()
})
