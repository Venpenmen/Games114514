import {expect,test,type Page} from '@playwright/test'

test('real exchange and mirror reaction gate their corresponding animations',async({browser})=>{
  const baseURL='http://127.0.0.1:3215'
  const contexts=await Promise.all(Array.from({length:4},(_,i)=>browser.newContext({baseURL,
    viewport:i===2?{width:390,height:844}:{width:1280,height:900}})))
  try{
    const pages=await Promise.all(contexts.map(context=>context.newPage()))
    const [a,b,c,d]=pages
    const btn=(page:Page,name:string)=>page.getByRole('button',{name,exact:true})
    const stage=(page:Page)=>page.locator('.nn-header > div:first-child > h2')
    async function login(page:Page,name:string,url=baseURL){
      await page.goto(url)
      await page.getByRole('textbox',{name:'昵称'}).fill(name)
      await btn(page,'保存资料').click()
    }
    async function select(page:Page,choice?:string){
      const controls=page.locator('.nn-options')
      await (choice?page.getByRole('button',{name:choice,exact:true}):controls.locator('button[aria-pressed]').first()).click()
      await btn(page,'确认提交').click()
    }
    await login(a,'甲')
    await a.getByRole('heading',{name:'忍者之夜',exact:true}).locator('..').getByRole('button',{name:'创建房间'}).click()
    await expect(a.locator('.members li')).toHaveCount(1)
    const link=a.url()
    for(const [i,page] of [b,c,d].entries()){
      await login(page,['乙','丙','丁'][i],link)
      await expect(a.locator('.members li')).toHaveCount(i+2)
    }
    await Promise.all(pages.map(async(page,i)=>{await btn(page,'肖像 '+(i+1)).click();await btn(page,'准备').click()}))
    await expect(a.getByText(/在线 · 已准备/)).toHaveCount(4)
    await btn(a,'开始游戏').click()
    await expect(stage(a)).toHaveText('第一步轮抽')
    await expect(a.locator('.nn-private-toast .nn-identity-card')).toContainText('你的本轮身份')
    await expect(a.getByRole('button',{name:'本轮复盘'})).toHaveCount(0)
    await Promise.all(pages.map(page=>btn(page,'确定').click()))
    await expect(a.locator('.nn-action-deck button .nn-card-face')).toHaveCount(3)
    await expect(a.getByRole('button',{name:'确认提交'})).toBeDisabled()
    await btn(a,'阶段帮助').click()
    await expect(a.getByRole('dialog')).toContainText('其余两张向左传')
    await btn(a,'一分钟入门').click()
    await expect(a.getByRole('dialog')).toContainText('积累 10 分荣誉')
    await btn(a,'卡牌与技能图鉴').click()
    await expect(a.locator('.nn-guide-skill')).toHaveCount(13)
    await btn(a,'完整玩法指南').click()
    await expect(a.getByRole('dialog')).toContainText('夜晚的五个阶段')
    await expect(a.getByRole('dialog')).toContainText('审判者的处决不能反应')
    await a.screenshot({path:'work/logs/ninja-p20-rules.png'})
    await a.keyboard.press('Escape')
    await expect(btn(a,'阶段帮助')).toBeFocused()
    const card=btn(a,'保留 变形者 1')
    const resting=(await card.boundingBox())!.y
    await card.click()
    await expect(card).toHaveAttribute('aria-pressed','true')
    await expect.poll(async()=>(await card.boundingBox())!.y).toBeLessThan(resting-3)
    await card.click()
    await expect(btn(a,'确认提交')).toBeDisabled()
    await a.evaluate(()=>{
      new MutationObserver((_,observer)=>{
        const cards=document.querySelectorAll('.nn-paths[data-kind=draft-pass] img')
        if(!cards.length) return
        document.documentElement.dataset.passCards=String(cards.length)
        observer.disconnect()
      }).observe(document.querySelector('.nn-ring')!,{childList:true})
    })
    await Promise.all([select(a,'保留 变形者 1'),select(b,'保留 盲眼刺客 4'),select(c,'保留 镜僧 1'),select(d)])
    await expect(stage(a)).toHaveText('第二步轮抽')
    await expect(a.locator('.nn-action-deck button .nn-card-face')).toHaveCount(2)
    await expect(a.getByText('第一步已保留 · 已锁定')).toBeVisible()
    await expect(a.locator('html')).toHaveAttribute('data-pass-cards','8')
    await a.reload()
    await expect(stage(a)).toHaveText('第二步轮抽')
    await expect(a.locator('[data-kind=draft-pass]')).toHaveCount(0)
    await Promise.all([select(a),select(b),select(c,'保留 隐士 3'),select(d)])
    await expect(a.locator('.nn-header > div:first-child [data-phase]')).toContainText('密探')
    await Promise.all(pages.map(page=>select(page,'跳过')))
    await expect(a.locator('.nn-header > div:first-child [data-phase]')).toContainText('隐士')
    await Promise.all([select(c,'打出 隐士 3'),...[a,b,d].map(page=>select(page,'跳过'))])
    await select(c,'甲')
    await btn(d,'公开时间线').click()
    await expect(d.locator('.nn-timeline [data-kind=reveal-batch]')).toContainText('隐士阶段 · 同时亮牌')
    const target=d.locator('.nn-timeline [data-kind=target]')
    await expect(target).toContainText(/丙.*甲/s)
    await expect(target).not.toContainText(/鹤派|莲派|镜僧/)
    const execution=await target.getAttribute('data-execution')
    expect(execution).toBeTruthy()
    await expect(d.locator('.nn-timeline [data-kind=play][data-execution="'+execution+'"]')).toContainText('隐士')
    await d.keyboard.press('Escape')
    const toast=(page:Page)=>page.locator('.nn-private-toast')
    await expect(toast(c)).toContainText('甲')
    await btn(c,'确定').click()
    await expect(toast(c)).toHaveCount(0)
    await expect(toast(a)).toContainText('丙 查看了你的')
    await expect(toast(a).locator('.nn-card-face').first()).toContainText('隐士')
    await a.waitForTimeout(2300)
    await expect(toast(a)).toBeVisible()
    await expect(toast(a)).toHaveCount(0,{timeout:9000})
    await btn(c,'私人情报').click()
    const inspected=c.locator('.nn-intel-list .nn-card-face')
    await expect(inspected).toHaveCount(1)
    const inspectedCard=await inspected.innerText()
    await c.keyboard.press('Escape')
    await a.reload()
    await expect(a.locator('.nn-letter')).toHaveCount(0)
    await btn(a,'私人情报').click()
    await expect(a.locator('.nn-intel-list')).toContainText('丙 查看了你的这张手牌')
    await expect(a.locator('.nn-intel-list .nn-card-face').last()).toHaveText(inspectedCard.replace(/\n/g,' '),{useInnerText:true})
    await expect(a.locator('.nn-intel-list .nn-identity-card')).toHaveCount(0)
    await a.keyboard.press('Escape')
    await btn(d,'私人情报').click()
    await expect(d.locator('.nn-intel-list')).toHaveCount(0)
    await d.keyboard.press('Escape')
    await expect(a.locator('.nn-header > div:first-child [data-phase]')).toContainText('骗徒')
    await Promise.all([select(a,'打出 变形者 1'),...[b,c,d].map(page=>select(page,'跳过'))])
    await expect(a.locator('.nn-active-effect')).toContainText('交换')
    await select(a,'乙')
    await expect(a.locator('.nn-target-trail')).toContainText('目标 1 · 乙')
    await expect(a.locator('.nn-seats').getByRole('button',{name:'乙',exact:true})).toBeDisabled()
    await expect(b.locator('.nn-target-trail')).toHaveCount(0)
    await select(a,'丙')
    await expect(a.locator('.nn-decision-intel .nn-identity-card')).toHaveCount(2)
    await expect(toast(a)).toContainText('乙')
    await btn(a,'确定').click()
    await expect(toast(a)).toContainText('丙')
    await btn(a,'确定').click()
    await expect(toast(a)).toHaveCount(0)
    await expect(b.locator('.nn-decision-intel')).toHaveCount(0)
    await expect(b.locator('.nn-event[data-event=swap]')).toHaveCount(0)
    await select(a,'交换')
    await expect(b.locator('.nn-event[data-event=swap]')).toContainText(/乙.*丙/s)
    await expect(b.locator('.nn-event[data-event=swap]')).not.toContainText(/鹤派|莲派/)
    await expect(b.locator('.nn-paths[data-kind=swap] span')).toHaveCount(2)
    await expect(c.getByText(/身份可能变化/).first()).toBeVisible()
    await btn(a,'私人情报').click()
    await expect(a.locator('.nn-intel-list .nn-identity-card')).toHaveCount(2)
    await expect(a.locator('.nn-intel-list')).toContainText('取得时的身份')
    await a.screenshot({path:'work/logs/ninja-p20-intel.png'})
    await a.keyboard.press('Escape')
    await expect(a.locator('.nn-header > div:first-child [data-phase]')).toContainText('盲眼刺客')
    await Promise.all([select(b,'打出 盲眼刺客 4'),...[a,c,d].map(page=>select(page,'跳过'))])
    await b.setViewportSize({width:390,height:844})
    await select(b,'丙')
    await expect(stage(c)).toHaveText('刺杀反应')
    await expect(c.locator('.nn-seat.nn-dead')).toHaveCount(0)
    await expect(c.locator('.nn-operation')).toContainText('不使用反应')
    await expect(c.locator('.nn-clock')).toBeVisible()
    await expect(c.locator('.nn-confirm')).toHaveCSS('position','fixed')
    await expect(a.locator('.nn-choice-card')).toHaveCount(0)
    await expect(c.locator('.nn-event[data-event=attack]')).toBeVisible()
    await expect(c.locator('.nn-event[data-event=death]')).toHaveCount(0)
    const confirmRect=await btn(c,'确认提交').boundingBox()
    const chatRect=await c.locator('.room-chat-toggle').boundingBox()
    expect(chatRect!.x).toBeGreaterThanOrEqual(confirmRect!.x+confirmRect!.width)
    await c.screenshot({path:'work/logs/ninja-p20-reaction-mobile.png'})
    await select(c,'发动 镜僧 1')
    await expect(a.locator('.nn-event[data-event=mirror]')).toBeVisible()
    await expect(a.locator('.nn-seat.nn-dead')).toHaveCount(0)
    await expect(a.locator('.nn-event[data-event=death]')).toBeVisible()
    await expect(a.locator('.nn-seat.nn-dead')).toContainText('乙')
    const barrier=await a.locator('.nn-game').getAttribute('data-presentation')
    expect(barrier).toBeTruthy()
    await expect(stage(b)).toHaveText('公开演出')
    await expect(a.locator('.nn-options')).toHaveCount(0)
    await a.reload()
    await expect(a.locator('.nn-seat.nn-dead')).toContainText('乙')
    await expect(a.locator('.nn-game')).toHaveAttribute('data-presentation',barrier!)
    await expect(a.locator('.nn-event[data-event=death]')).toBeVisible()
    await expect(a.locator('.nn-header > div:first-child [data-phase]')).toContainText('上忍')
    await Promise.all([a,c,d].map(page=>select(page,'跳过')))
    await expect(stage(a)).toHaveText('下一轮准备',{timeout:16000})
    await btn(d,'本轮复盘').click()
    const recap=d.getByRole('dialog',{name:'本轮复盘'})
    await expect(recap).toBeVisible()
    await expect(recap.locator('[data-step=target]').first()).toContainText(/丙.*甲/s)
    await expect(recap.locator('[data-step=deal], [data-step=draft1], [data-step=intel], [data-step=round-score]')).toHaveCount(0)
    await expect(recap.locator('.nn-honor')).toHaveCount(0)
    await d.keyboard.press('Escape')
    await Promise.all(pages.map(page=>select(page)))
    await expect(stage(a)).toHaveText('第一步轮抽')
    await expect(a.locator('.nn-header')).toContainText('第 2 轮')
    await expect(a.locator('.nn-private-toast .nn-identity-card')).toContainText('你的本轮身份')
    await expect(a.getByRole('button',{name:'本轮复盘'})).toHaveCount(0)
    await a.reload()
    await expect(stage(a)).toHaveText('第一步轮抽')
    await expect(a.locator('.nn-private-toast')).toHaveCount(0)
    await btn(a,'私人情报').click()
    await expect(a.locator('.nn-intel-list')).toHaveCount(0)
    await a.keyboard.press('Escape')
    await btn(a,'公开时间线').click()
    await expect(a.locator('.nn-timeline li')).toHaveCount(1)
    await expect(a.locator('.nn-timeline')).toContainText('第 2 轮')
    await expect(a.getByRole('button',{name:'完整复盘'})).toHaveCount(0)
  }finally{await Promise.all(contexts.map(context=>context.close()))}
})
